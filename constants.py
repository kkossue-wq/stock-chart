def is_korean(ticker: str) -> bool:
    return ".KS" in ticker or ".KQ" in ticker


def currency_symbol(ticker: str) -> str:
    return "₩" if is_korean(ticker) else "$"


def currency_name(ticker: str) -> str:
    return "원" if is_korean(ticker) else "USD"


def format_price(price: float, ticker: str) -> str:
    if is_korean(ticker):
        return f"₩{price:,.0f}"
    return f"${price:,.2f}"
